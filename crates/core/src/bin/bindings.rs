use std::{collections::BTreeMap, fs, path::Path};

use cataland_core::{ClientView, Request, Response, RoomInfo};
use ts_rs::{Config, TS, TypeVisitor};

#[derive(Default)]
struct Bindings(BTreeMap<String, String>);

impl TypeVisitor for Bindings {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() {
            T::visit_dependencies(self);
            return;
        }
        let config = Config::new().with_large_int("number");
        let name = T::ident(&config);
        if self.0.contains_key(&name) {
            return;
        }
        self.0.insert(name, format!("export {}", T::decl(&config)));
        T::visit_dependencies(self);
    }
}

fn main() -> std::io::Result<()> {
    let mut bindings = Bindings::default();
    bindings.visit::<ClientView>();
    bindings.visit::<Request>();
    bindings.visit::<Response>();
    bindings.visit::<RoomInfo>();
    let output = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/bindings.ts");
    fs::write(
        output,
        format!(
            "// Generated by pnpm bindings.\n\n{}\n",
            bindings.0.into_values().collect::<Vec<_>>().join("\n\n")
        ),
    )
}
